//为所有大数组、缓冲区在psram中分配空间
void alloc_psram_buffers(void) 
{
    uint16_t eedata_size = EEDATA_SIZE;
    uint16_t frame_size = FRAME_SIZE;
    uint16_t matrix_size = MATRIX_SIZE;
    uint32_t image_size = IMAGE_WIDTH * IMAGE_HEIGHT;
    uint32_t screen_size = LCD_WIDTH * LCD_HEIGHT;
    eeData = heap_caps_malloc(eedata_size * sizeof(uint16_t), MALLOC_CAP_SPIRAM);
    FrameData[0] = heap_caps_malloc(frame_size * sizeof(uint16_t), MALLOC_CAP_SPIRAM);
    FrameData[1] = heap_caps_malloc(frame_size * sizeof(uint16_t), MALLOC_CAP_SPIRAM);
    OriginalDataMatrix = heap_caps_malloc(matrix_size * sizeof(float), MALLOC_CAP_SPIRAM);
    RotatedDataMatrix = heap_caps_malloc(matrix_size * sizeof(float), MALLOC_CAP_SPIRAM);
    InterpolationDataMatrix = heap_caps_malloc(image_size * sizeof(float), MALLOC_CAP_SPIRAM);
    GrayValueMatrix = heap_caps_malloc(image_size * sizeof(uint8_t), MALLOC_CAP_SPIRAM);
    RGBValueMatrix = heap_caps_malloc(image_size * sizeof(uint16_t), MALLOC_CAP_SPIRAM);
    DisplayBuffer = heap_caps_malloc(screen_size * sizeof(uint16_t), MALLOC_CAP_INTERNAL | MALLOC_CAP_DMA);
}

void Set_Color_Scheme(color_scheme_t scheme)
{
    if (scheme < COLOR_SCHEME_COUNT) 
    {
        g_current_color_lut = g_color_luts[scheme];
        Draw_Color_Strip();
    }
}

void Pseudo_Color_Fast(uint8_t *grayImage, uint16_t *rgb565Image)
{
    uint32_t total = IMAGE_WIDTH * IMAGE_HEIGHT;
    const uint16_t *lut = g_current_color_lut;
    for (uint32_t i = 0; i < total; i++) 
    {
        rgb565Image[i] = lut[grayImage[i]];
    }
}

void Color_Scheme_Init(void)
{
    switch (scheme_idx)
    {
        case SCHEME_GRAY_INDEX:
            Set_Color_Scheme(COLOR_SCHEME_GRAY);
            break;
        case SCHEME_METAL_INDEX:
            Set_Color_Scheme(COLOR_SCHEME_METAL);
            break;
        case SCHEME_PSEUDO1_INDEX:
            Set_Color_Scheme(COLOR_SCHEME_PSEUDO1);
            break;
        case SCHEME_PSEUDO2_INDEX:
            Set_Color_Scheme(COLOR_SCHEME_PSEUDO2);
            break;
        case SCHEME_RAINBOW1_INDEX:
            Set_Color_Scheme(COLOR_SCHEME_RAINBOW1);
            break;
        case SCHEME_RAINBOW2_INDEX:
            Set_Color_Scheme(COLOR_SCHEME_RAINBOW2);
            break;
    }
}

void init_sync_objects(void) 
{
    raw_ready_queue = xQueueCreate(FRAME_BUF_COUNT, sizeof(uint8_t));
    raw_free_sem = xSemaphoreCreateCounting(FRAME_BUF_COUNT, FRAME_BUF_COUNT);   // 2个原始缓冲区初始空闲
    display_mutex = xSemaphoreCreateMutex();
    image_mutex = xSemaphoreCreateMutex();
}